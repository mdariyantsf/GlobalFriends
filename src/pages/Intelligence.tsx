import { useMemo, useState } from "react";
import { BookOpenCheck, Compass, ListChecks, Sparkles } from "lucide-react";
import { createLearningRoadmap } from "../lib/intelligence";
import Notice from "../components/Notice";

const splitValues = (value: string) => value.split(",").map((item) => item.trim()).filter(Boolean).slice(0, 12);

export default function Intelligence() {
  const [goal, setGoal] = useState("");
  const [skillsText, setSkillsText] = useState("");
  const [interestsText, setInterestsText] = useState("");
  const [generated, setGenerated] = useState(false);
  const skills = useMemo(() => splitValues(skillsText), [skillsText]);
  const interests = useMemo(() => splitValues(interestsText), [interestsText]);
  const roadmap = useMemo(() => createLearningRoadmap(goal, skills, interests), [goal, skills, interests]);

  return <div className="gf-page">
    <section className="mb-8 rounded-[26px] bg-gradient-to-br from-forest-950 via-forest-800 to-emerald-700 p-7 text-white md:p-10">
      <div className="mb-4 inline-flex items-center gap-2 rounded-full border border-white/20 bg-white/10 px-3 py-1 text-xs font-bold text-emerald-100"><Sparkles size={14}/> GLOBAL INTELLIGENCE</div>
      <h1 className="text-3xl font-extrabold md:text-4xl">Turn curiosity into a learning plan.</h1>
      <p className="mt-3 max-w-2xl leading-7 text-emerald-50/90">A transparent, code-powered guide that helps you break a learning goal into practical next steps—without sending your information to an AI service.</p>
    </section>

    <div className="grid gap-6 lg:grid-cols-[.9fr_1.1fr]">
      <section className="gf-card p-6">
        <div className="mb-5 flex items-center gap-3"><div className="rounded-xl bg-emerald-50 p-3 text-forest-700"><Compass size={21}/></div><div><h2 className="font-extrabold text-forest-950">Your learning profile</h2><p className="text-sm gf-muted">Only used in this page to prepare your plan.</p></div></div>
        <label className="gf-label" htmlFor="learning-goal">What do you want to achieve?</label>
        <textarea id="learning-goal" className="gf-input min-h-24 resize-y" maxLength={240} placeholder="Example: Build a website for a student science project" value={goal} onChange={(event) => { setGoal(event.target.value); setGenerated(false); }}/>
        <label className="gf-label mt-4" htmlFor="current-skills">Skills you already have (comma-separated)</label>
        <input id="current-skills" className="gf-input" maxLength={240} placeholder="Example: HTML, writing, research" value={skillsText} onChange={(event) => { setSkillsText(event.target.value); setGenerated(false); }}/>
        <label className="gf-label mt-4" htmlFor="interests">Your interests (comma-separated)</label>
        <input id="interests" className="gf-input" maxLength={240} placeholder="Example: climate, design, technology" value={interestsText} onChange={(event) => { setInterestsText(event.target.value); setGenerated(false); }}/>
        <button className="gf-button mt-5 w-full" onClick={() => setGenerated(true)} disabled={!goal.trim()}> <ListChecks size={17}/> Create my roadmap</button>
        {!goal.trim() && <p className="mt-2 text-xs gf-muted">Enter a learning goal to create a plan.</p>}
      </section>

      <section className="gf-card p-6">
        <div className="mb-5 flex items-center gap-3"><div className="rounded-xl bg-emerald-50 p-3 text-forest-700"><BookOpenCheck size={21}/></div><div><p className="text-xs font-bold uppercase tracking-wider text-forest-700">Your roadmap</p><h2 className="font-extrabold text-forest-950">{roadmap.title}</h2></div></div>
        {generated ? <div className="mb-4"><Notice kind="success">Your plan is ready. You can adjust your goal or skills to create another version.</Notice></div> : <div className="mb-4"><Notice>Enter a goal and select “Create my roadmap” to prepare your learning steps.</Notice></div>}
        <ol className="space-y-4">
          {roadmap.steps.map((step, index) => <li key={step.title} className="flex gap-3"><span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full bg-emerald-100 text-sm font-extrabold text-forest-800">{index + 1}</span><div><h3 className="font-bold text-forest-950">{step.title}</h3><p className="mt-1 text-sm leading-6 gf-muted">{step.description}</p><p className="mt-1 text-xs font-semibold text-forest-700">Outcome: {step.outcome}</p></div></li>)}
        </ol>
        <p className="mt-4 text-xs leading-5 gf-muted">{roadmap.context}</p>
        <p className="mt-5 border-t border-emerald-100 pt-4 text-xs leading-5 gf-muted">Method note: this roadmap is selected from hand-written learning templates using keyword rules. It is not generated by an AI model and may need to be adapted with help from a teacher or mentor.</p>
      </section>
    </div>
    <div className="mt-6"><Notice>Privacy: your entries stay in this page and are not sent to an external service or saved to the database.</Notice></div>
  </div>;
}
